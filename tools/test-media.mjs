// Regressions: explicit pause controls, tab visibility and reduced-motion changes.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const events=()=>({handlers:{},addEventListener(name,handler){this.handlers[name]=handler}});
const video={...events(),paused:true,dataset:{desktop:'desktop.mp4',mobile:'mobile.mp4'},getAttribute(){return this.src},play(){this.paused=false;this.handlers.play?.();return Promise.resolve()},pause(){this.paused=true;this.handlers.pause?.()}};
const videoButton={...events(),hidden:true};
const videoMotion={...events(),matches:false};
const document={...events(),hidden:false,querySelector:selector=>({'#hero-video':video,'#video-toggle':videoButton}[selector]??null),querySelectorAll:()=>[]};
vm.runInNewContext(readFileSync('assets/app.js','utf8'),{document,navigator:{},matchMedia:()=>videoMotion});
assert.equal(video.paused,false);
videoButton.handlers.click();assert.equal(video.paused,true);
document.hidden=true;document.handlers.visibilitychange();document.hidden=false;document.handlers.visibilitychange();assert.equal(video.paused,true,'manual pause survives tab switch');
videoButton.handlers.click();assert.equal(video.paused,false);
document.hidden=true;document.handlers.visibilitychange();assert.equal(video.paused,true);
document.hidden=false;document.handlers.visibilitychange();assert.equal(video.paused,false,'playing video resumes on return');
videoMotion.matches=true;videoMotion.handlers.change();assert.equal(video.paused,true,'reduced motion pauses video');
console.log('PASS video pause, play, visibility and reduced motion');
const rail={...events(),scrollLeft:0,contains:()=>false};
const railButton={...events(),hidden:true};
const railMotion={...events(),matches:false};
let scheduled=0;
const railDocument={...events(),hidden:false,querySelector:selector=>({'#production-rail':rail,'#production-toggle':railButton}[selector]??null)};
vm.runInNewContext(readFileSync('assets/motion.js','utf8'),{document:railDocument,window:{},matchMedia:()=>railMotion,requestAnimationFrame:()=>++scheduled,cancelAnimationFrame(){}});
assert.equal(railButton.hidden,false);assert.equal(railButton.textContent,'Pause scrolling');assert.ok(scheduled);
railButton.handlers.click();assert.equal(railButton.textContent,'Play scrolling');
railButton.handlers.click();assert.equal(railButton.textContent,'Pause scrolling');
railMotion.matches=true;railMotion.handlers.change();assert.equal(railButton.textContent,'Play scrolling');
console.log('PASS production pause, play, reduced motion and observer fallback');
